// Builds the common viewers (apps/web/app/viewers/pdf and viewers/video) into
// one script and one stylesheet each, committed as generated TypeScript
// strings that the sandbox Worker serves at /__as_pdf/viewer.{js,css} and
// /__as_video/viewer.{js,css} on every PDF or video version's origin.
// `--check` compares without writing and fails when any output is missing or
// stale. Name viewers (`pdf`, `video`) to build only those.
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'
import tailwindcss from '@tailwindcss/vite'
import { build } from 'vite'

const webRoot = fileURLToPath(new URL('..', import.meta.url))
const appRoot = resolve(webRoot, 'app')
const i18nRoot = resolve(appRoot, 'i18n')
const REGENERATE = 'pnpm --filter @artifactshare/web generate:viewers'
const pdfRoot = resolve(appRoot, 'viewers/pdf')
const videoRoot = resolve(appRoot, 'viewers/video')

// Each viewer's module entry is its bundle `input`, written out per viewer
// with a file name of its own: that is also how react-doctor finds the
// viewer sources from this script, and it skips a name two viewers share.
export const viewers = {
  pdf: {
    label: 'PDF viewer',
    root: pdfRoot,
    input: resolve(pdfRoot, 'entry.tsx'),
    messagePrefix: 'pdfViewer.',
    exports: { script: 'PDF_VIEWER_SCRIPT', style: 'PDF_VIEWER_STYLE' },
    outputs: {
      script: resolve(webRoot, 'workers/lib/pdf-viewer-script.generated.ts'),
      style: resolve(webRoot, 'workers/lib/pdf-viewer-style.generated.ts'),
    },
  },
  video: {
    label: 'video player',
    root: videoRoot,
    input: resolve(videoRoot, 'player-entry.tsx'),
    messagePrefix: 'videoViewer.',
    exports: { script: 'VIDEO_VIEWER_SCRIPT', style: 'VIDEO_VIEWER_STYLE' },
    outputs: {
      script: resolve(webRoot, 'workers/lib/video-viewer-script.generated.ts'),
      style: resolve(webRoot, 'workers/lib/video-viewer-style.generated.ts'),
    },
  },
}

// Each viewer reads its strings from the app's catalogs; only its own keys
// are bundled.
function viewerMessagesOnly(prefix) {
  return {
    name: 'viewer-messages',
    enforce: 'pre',
    transform(code, id) {
      const path = id.split('?')[0]
      if (!path.startsWith(`${i18nRoot}/`) || !path.endsWith('.json'))
        return null
      const catalog = JSON.parse(code)
      const viewerMessages = Object.fromEntries(
        Object.entries(catalog).filter(([key]) => key.startsWith(prefix)),
      )
      return { code: JSON.stringify(viewerMessages), map: null }
    },
  }
}

// One self-contained script and one stylesheet: anything else a viewer needs
// (pdf.js) stays a run-time import from the sandbox origin, and nothing else
// may be emitted or loaded.
export function pickBundle(outputs, label = 'viewer') {
  const chunks = outputs.filter((output) => output.type === 'chunk')
  const assets = outputs.filter((output) => output.type === 'asset')
  const [chunk] = chunks
  const [asset] = assets
  if (
    chunks.length !== 1 ||
    assets.length !== 1 ||
    chunk.fileName !== 'viewer.js' ||
    asset.fileName !== 'viewer.css'
  )
    throw new Error(
      `the ${label} must build to viewer.js and viewer.css only, not ${outputs.map((output) => output.fileName).join(', ')}`,
    )
  if (chunk.imports.length || chunk.dynamicImports.length)
    throw new Error(`the ${label} script must not import other chunks`)
  const style = String(asset.source)
  if (/@import|url\((?!\s*["']?data:)/i.test(style))
    throw new Error(`the ${label} stylesheet must not load other files`)
  return { script: chunk.code, style }
}

export async function renderViewer(name) {
  const viewer = viewers[name]
  if (!viewer) throw new Error(`unknown viewer ${name}`)
  const result = await build({
    configFile: false,
    envFile: false,
    logLevel: 'silent',
    mode: 'production',
    root: viewer.root,
    publicDir: false,
    plugins: [viewerMessagesOnly(viewer.messagePrefix), tailwindcss()],
    resolve: { alias: { '~': appRoot } },
    oxc: { jsx: { runtime: 'automatic' } },
    build: {
      write: false,
      minify: true,
      sourcemap: false,
      target: 'es2022',
      cssCodeSplit: false,
      modulePreload: false,
      reportCompressedSize: false,
      rolldownOptions: {
        input: viewer.input,
        output: {
          entryFileNames: 'viewer.js',
          assetFileNames: 'viewer.[ext]',
          codeSplitting: false,
        },
      },
    },
  })
  const outputs = (Array.isArray(result) ? result : [result]).flatMap(
    (entry) => entry.output,
  )
  const { script, style } = pickBundle(outputs, viewer.label)
  const source = (exportName, body) =>
    '// Generated by apps/web/scripts/build-viewers.mjs. Do not edit.\n' +
    `// Run ${REGENERATE} to regenerate.\n` +
    `export const ${exportName} = ${JSON.stringify(body)}\n`
  return {
    name,
    script,
    style,
    sources: {
      script: source(viewer.exports.script, script),
      style: source(viewer.exports.style, style),
    },
  }
}

async function readExisting(path) {
  try {
    return await readFile(path, 'utf8')
  } catch (error) {
    if (error.code === 'ENOENT') return null
    throw error
  }
}

// Compares the rendered sources with the committed files; writes the
// changed ones unless checking.
export async function writeViewer(
  rendered,
  { outputs = viewers[rendered.name].outputs, check = false } = {},
) {
  for (const kind of ['script', 'style']) {
    const existing = await readExisting(outputs[kind])
    if (existing === rendered.sources[kind]) continue
    if (check)
      throw new Error(`${outputs[kind]} is missing or stale; run ${REGENERATE}`)
    await writeFile(outputs[kind], rendered.sources[kind])
  }
  return rendered
}

if (import.meta.main) {
  const check = process.argv.includes('--check')
  const named = process.argv.slice(2).filter((arg) => !arg.startsWith('--'))
  const size = (body) =>
    `${Buffer.byteLength(body, 'utf8')} bytes (${gzipSync(body).length} gzip)`
  try {
    for (const name of named.length ? named : Object.keys(viewers)) {
      const rendered = await writeViewer(await renderViewer(name), { check })
      console.log(
        `${viewers[name].label} ${check ? 'is current' : 'generated'}: viewer.js ${size(rendered.script)}, viewer.css ${size(rendered.style)}`,
      )
    }
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
