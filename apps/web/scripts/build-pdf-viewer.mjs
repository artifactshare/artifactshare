// Builds the PDF viewer (apps/web/app/viewers/pdf) into one script and one
// stylesheet, committed as generated TypeScript strings that the sandbox
// Worker serves at /__as_pdf/viewer.js and /__as_pdf/viewer.css on every PDF
// version's origin. `--check` compares without writing and fails when either
// output is missing or stale.
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'
import tailwindcss from '@tailwindcss/vite'
import { build } from 'vite'

const webRoot = fileURLToPath(new URL('..', import.meta.url))
const appRoot = resolve(webRoot, 'app')
const viewerRoot = resolve(appRoot, 'viewers/pdf')
const i18nRoot = resolve(appRoot, 'i18n')
const MESSAGE_PREFIX = 'pdfViewer.'
const REGENERATE = 'pnpm --filter @artifactshare/web generate:pdf-viewer'

export const outputPaths = {
  script: resolve(webRoot, 'workers/lib/pdf-viewer-script.generated.ts'),
  style: resolve(webRoot, 'workers/lib/pdf-viewer-style.generated.ts'),
}

// The viewer reads its strings from the app's catalogs; only its own keys
// are bundled.
function viewerMessagesOnly() {
  return {
    name: 'pdf-viewer-messages',
    enforce: 'pre',
    transform(code, id) {
      const path = id.split('?')[0]
      if (!path.startsWith(`${i18nRoot}/`) || !path.endsWith('.json'))
        return null
      const catalog = JSON.parse(code)
      const viewerMessages = Object.fromEntries(
        Object.entries(catalog).filter(([key]) =>
          key.startsWith(MESSAGE_PREFIX),
        ),
      )
      return { code: JSON.stringify(viewerMessages), map: null }
    },
  }
}

// One self-contained script and one stylesheet: pdf.js stays a run-time
// import from the sandbox origin, and nothing else may be emitted or loaded.
export function pickBundle(outputs) {
  const chunks = outputs.filter((output) => output.type === 'chunk')
  const assets = outputs.filter((output) => output.type === 'asset')
  const [chunk] = chunks
  const [asset] = assets
  if (
    chunks.length !== 1 ||
    assets.length !== 1 ||
    chunk.fileName !== 'viewer.js' ||
    asset.fileName !== 'viewer.css'
  )
    throw new Error(
      `the PDF viewer must build to viewer.js and viewer.css only, not ${outputs.map((output) => output.fileName).join(', ')}`,
    )
  if (chunk.imports.length || chunk.dynamicImports.length)
    throw new Error('the PDF viewer script must not import other chunks')
  const style = String(asset.source)
  if (/@import|url\((?!\s*["']?data:)/i.test(style))
    throw new Error('the PDF viewer stylesheet must not load other files')
  return { script: chunk.code, style }
}

export async function renderPdfViewer() {
  const result = await build({
    configFile: false,
    envFile: false,
    logLevel: 'silent',
    mode: 'production',
    root: viewerRoot,
    publicDir: false,
    plugins: [viewerMessagesOnly(), tailwindcss()],
    resolve: { alias: { '~': appRoot } },
    oxc: { jsx: { runtime: 'automatic' } },
    build: {
      write: false,
      minify: true,
      sourcemap: false,
      target: 'es2022',
      cssCodeSplit: false,
      modulePreload: false,
      reportCompressedSize: false,
      rolldownOptions: {
        input: resolve(viewerRoot, 'entry.tsx'),
        output: {
          entryFileNames: 'viewer.js',
          assetFileNames: 'viewer.[ext]',
          codeSplitting: false,
        },
      },
    },
  })
  const outputs = (Array.isArray(result) ? result : [result]).flatMap(
    (entry) => entry.output,
  )
  const { script, style } = pickBundle(outputs)
  const source = (name, body) =>
    '// Generated by apps/web/scripts/build-pdf-viewer.mjs. Do not edit.\n' +
    `// Run ${REGENERATE} to regenerate.\n` +
    `export const ${name} = ${JSON.stringify(body)}\n`
  return {
    script,
    style,
    sources: {
      script: source('PDF_VIEWER_SCRIPT', script),
      style: source('PDF_VIEWER_STYLE', style),
    },
  }
}

async function readExisting(path) {
  try {
    return await readFile(path, 'utf8')
  } catch (error) {
    if (error.code === 'ENOENT') return null
    throw error
  }
}

// Compares the rendered sources with the committed files; writes the
// changed ones unless checking.
export async function writePdfViewer(
  rendered,
  { outputs = outputPaths, check = false } = {},
) {
  for (const kind of ['script', 'style']) {
    const existing = await readExisting(outputs[kind])
    if (existing === rendered.sources[kind]) continue
    if (check)
      throw new Error(`${outputs[kind]} is missing or stale; run ${REGENERATE}`)
    await writeFile(outputs[kind], rendered.sources[kind])
  }
  return rendered
}

if (import.meta.main) {
  const check = process.argv.includes('--check')
  try {
    const rendered = await writePdfViewer(await renderPdfViewer(), { check })
    const size = (body) =>
      `${Buffer.byteLength(body, 'utf8')} bytes (${gzipSync(body).length} gzip)`
    console.log(
      `PDF viewer ${check ? 'is current' : 'generated'}: viewer.js ${size(rendered.script)}, viewer.css ${size(rendered.style)}`,
    )
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
