// Generates src/preview/messages.generated.ts from the web app dictionaries.
// The web en/ja catalogs are the single source of preview UI copy; this
// script extracts the preview.* subset at build time so the CLI bundle
// carries no runtime dependency on apps/web.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const webI18n = join(here, '..', '..', '..', 'apps', 'web', 'app', 'i18n')
const out = join(here, '..', 'src', 'preview', 'messages.generated.ts')

const locales = ['en', 'ja']
const catalogs = {}
for (const locale of locales) {
  const full = JSON.parse(readFileSync(join(webI18n, locale + '.json'), 'utf8'))
  const subset = {}
  for (const [key, value] of Object.entries(full)) {
    if (key.startsWith('preview.')) subset[key] = value
  }
  catalogs[locale] = subset
}
const enKeys = Object.keys(catalogs.en).sort()
const jaKeys = Object.keys(catalogs.ja).sort()
if (JSON.stringify(enKeys) !== JSON.stringify(jaKeys)) {
  console.error('preview.* keys differ between en and ja catalogs')
  process.exit(1)
}
if (enKeys.length === 0) {
  console.error('no preview.* keys found in the web catalogs')
  process.exit(1)
}
const body =
  '// Generated by scripts/generate-preview-messages.mjs - do not edit.\n' +
  '// Source: apps/web/app/i18n/{en,ja}.json (preview.* subset).\n' +
  'export const PREVIEW_MESSAGES = ' +
  JSON.stringify(catalogs, null, 2) +
  ' as const\n' +
  '\n' +
  'export type PreviewMessageKey = keyof (typeof PREVIEW_MESSAGES)[\'en\']\n'
writeFileSync(out, body)
console.log('wrote', out, enKeys.length, 'keys')
