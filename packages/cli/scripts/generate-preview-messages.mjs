// Generates src/preview/messages.generated.ts from the web app dictionaries.
// The web en/ja catalogs are the single source of preview UI copy; this
// script extracts the preview.* subset at build time so the CLI bundle
// carries no runtime dependency on apps/web.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const webI18n = join(here, '..', '..', '..', 'apps', 'web', 'app', 'i18n')
const out = join(here, '..', 'src', 'preview', 'messages.generated.ts')

const locales = ['en', 'ja']
const catalogs = {}
for (const locale of locales) {
  const full = JSON.parse(readFileSync(join(webI18n, locale + '.json'), 'utf8'))
  const subset = {}
  for (const [key, value] of Object.entries(full)) {
    if (key.startsWith('preview.')) subset[key] = value
  }
  catalogs[locale] = subset
}
const enKeys = Object.keys(catalogs.en).sort()
const jaKeys = Object.keys(catalogs.ja).sort()
if (JSON.stringify(enKeys) !== JSON.stringify(jaKeys)) {
  console.error('preview.* keys differ between en and ja catalogs')
  process.exit(1)
}
if (enKeys.length === 0) {
  console.error('no preview.* keys found in the web catalogs')
  process.exit(1)
}
// Emit the repository formatter's shape directly (single quotes, bare
// identifier keys, trailing commas) so a rebuild never dirties the tree.
function quote(value) {
  // JSON.stringify already escapes quotes, backslashes, and the line
  // terminators that would otherwise emit an unterminated string literal.
  return JSON.stringify(value)
}
function serialize(value, indent) {
  const pad = '  '.repeat(indent)
  const inner = '  '.repeat(indent + 1)
  const entries = Object.entries(value).map(([key, item]) => {
    const printedKey = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : quote(key)
    const printedValue =
      typeof item === 'string' ? quote(item) : serialize(item, indent + 1)
    return inner + printedKey + ': ' + printedValue + ','
  })
  return '{\n' + entries.join('\n') + '\n' + pad + '}'
}
const body =
  '// Generated by scripts/generate-preview-messages.mjs - do not edit.\n' +
  '// Source: apps/web/app/i18n/{en,ja}.json (preview.* subset).\n' +
  'export const PREVIEW_MESSAGES = ' +
  serialize(catalogs, 0) +
  ' as const\n' +
  '\n' +
  "export type PreviewMessageKey = keyof (typeof PREVIEW_MESSAGES)['en']\n"
writeFileSync(out, body)

// Normalize to the repository formatter so a rebuild never dirties the tree.
const repoRoot = join(here, '..', '..', '..')
const fmt = spawnSync(
  'pnpm',
  ['exec', 'vp', 'fmt', '-c', '.oxfmtrc.json', relative(repoRoot, out)],
  { cwd: repoRoot, stdio: 'ignore' },
)
if (fmt.status !== 0) {
  console.warn(
    'generate-preview-messages: formatter pass failed; output left unformatted',
  )
}
console.log('wrote', out, enKeys.length, 'keys')
