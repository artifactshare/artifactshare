import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { screens } from './screen-ledger.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
export const taskLedgerScreenReferencesPath = join(
  HERE,
  'task-ledger-screen-references.d.ts',
)

export function renderTaskLedgerScreenReferences(ledgerScreens = screens) {
  const references = new Set()
  for (const screen of ledgerScreens)
    for (const state of screen.states)
      references.add(`${screen.id}/${state.id}`)

  const lines = [
    '// Generated by scripts/generate-task-ledger-types.mjs from ScreenSpec exports.',
    '// Do not edit manually; run the task-ledger typecheck after changing a screen.',
    '',
    'export type TaskLedgerScreenReference =',
    ...[...references].sort().map((reference) => `  | '${reference}'`),
    '',
  ]
  return lines.join('\n')
}

export function generateTaskLedgerScreenReferences({
  outputPath = taskLedgerScreenReferencesPath,
  check = false,
} = {}) {
  const source = renderTaskLedgerScreenReferences()
  let existing = ''
  try {
    existing = readFileSync(outputPath, 'utf8')
  } catch (error) {
    if (error.code !== 'ENOENT') throw error
  }

  if (check) {
    if (existing !== source)
      throw new Error(
        `${outputPath} is stale; run node scripts/generate-task-ledger-types.mjs`,
      )
    return false
  }

  if (existing === source) return false
  writeFileSync(outputPath, source)
  return true
}

if (import.meta.main) {
  const check = process.argv.includes('--check')
  try {
    const changed = generateTaskLedgerScreenReferences({ check })
    console.log(
      check
        ? 'task-ledger screen reference types are current'
        : changed
          ? 'task-ledger screen reference types updated'
          : 'task-ledger screen reference types unchanged',
    )
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
